"""Export an approved handover as standalone HTML, Markdown or PDF (predefined templates)."""
from __future__ import annotations

import html
import io
import re
from datetime import datetime

SECTIONS = [
    ("completed", "Completed tasks"),
    ("ongoing", "Ongoing tasks"),
    ("pending", "Pending tasks"),
    ("decisions", "Technical decisions"),
    ("issues", "Known issues"),
    ("dependencies", "Dependencies"),
    ("contacts", "Who to ask"),
]


def _sources(c: dict) -> dict[int, str]:
    out = {}
    for key, _ in SECTIONS + [("overview_notes", "")]:
        for r in c.get(key, []):
            out[r["id"]] = r["source"]
    return out


def _item_line(r: dict) -> str:
    meta = [x for x in [r.get("status"), f"owner: {r['owner']}" if r.get("owner") else "",
                        f"priority: {r['priority']}" if r.get("priority") else ""] if x]
    s = r["title"]
    if meta:
        s += f" ({', '.join(meta)})"
    if r.get("rationale"):
        s += f" — why: {r['rationale']}"
    return s


def to_markdown(c: dict, meta: dict) -> str:
    L = [f"# Handover: {c['project']['name']}", "",
         f"**From:** {c.get('outgoing') or '-'}  ·  **To:** {c.get('incoming') or '-'}  ·  **Status:** {meta.get('status')}  ·  **Readiness:** {c.get('readiness', {}).get('score', 0)}%", "",
         "## Project overview", c.get("overview", ""), ""]
    L += ["## Recommended next steps"] + [f"{i}. {s}" for i, s in enumerate(c.get("next_steps", []), 1)] + [""]
    L += ["## First-week plan"] + [f"- {s}" for s in c.get("first_week", [])] + [""]
    for key, title in SECTIONS:
        L.append(f"## {title}")
        items = c.get(key, [])
        L += [f"- {_item_line(r)} [R{r['id']}] — _{r['source']}_" for r in items] or ["- None recorded."]
        L.append("")
    if c.get("risks"):
        L += ["## Risks"] + [f"- {r}" for r in c["risks"]] + [""]
    L += ["## Important documents"] + [f"- {d['filename']} ({d['records']} records)" for d in c.get("documents", [])] + [""]
    if c.get("answered_questions"):
        L += ["## Clarifications from the outgoing member"]
        for qa in c["answered_questions"]:
            L += [f"**Q:** {qa['q']}", f"**A:** {qa['a']}", ""]
    if c.get("open_questions"):
        L += ["## Still unanswered"] + [f"- ({q['severity']}) {q['q']}" for q in c["open_questions"]] + [""]
    L.append(f"_Generated by ContinuityIQ on {datetime.now():%d %b %Y %H:%M}. Every [R#] links to a reviewed source record._")
    return "\n".join(L)


def to_html(c: dict, meta: dict) -> str:
    src = _sources(c)
    esc = html.escape

    def cite(text: str) -> str:
        t = esc(text)
        return re.sub(r"\[R(\d+)\]", lambda m: f'<sup class="cite" title="{esc(src.get(int(m.group(1)), "source record"))}">R{m.group(1)}</sup>', t)

    def items(key):
        rows = c.get(key, [])
        if not rows:
            return '<p class="muted">None recorded.</p>'
        return "<ul>" + "".join(
            f'<li>{cite(_item_line(r))} <sup class="cite" title="{esc(r["source"])}">R{r["id"]}</sup>'
            f'<div class="src">{esc(r["source"])}</div></li>' for r in rows) + "</ul>"

    score = c.get("readiness", {}).get("score", 0)
    body = [f"""<header><div class="brand">ContinuityIQ · Handover report</div>
<h1>{esc(c['project']['name'])}</h1>
<div class="meta"><span>From <b>{esc(c.get('outgoing') or '-')}</b></span><span>To <b>{esc(c.get('incoming') or '-')}</b></span>
<span class="badge {esc(meta.get('status', 'draft'))}">{esc(meta.get('status', 'draft')).upper()}</span><span>Readiness <b>{score}%</b></span>
<span>v{meta.get('version', 1)}</span></div></header>""",
            f"<section><h2>Project overview</h2><p>{cite(c.get('overview', ''))}</p></section>",
            "<section class='grid2'><div><h2>Recommended next steps</h2><ol>" + "".join(f"<li>{cite(s)}</li>" for s in c.get("next_steps", [])) + "</ol></div>"
            "<div><h2>First-week plan</h2><ul>" + "".join(f"<li>{cite(s)}</li>" for s in c.get("first_week", [])) + "</ul></div></section>"]
    for key, title in SECTIONS:
        body.append(f"<section><h2>{title} <span class='count'>{len(c.get(key, []))}</span></h2>{items(key)}</section>")
    if c.get("risks"):
        body.append("<section><h2>Risks to watch</h2><ul>" + "".join(f"<li>{cite(r)}</li>" for r in c["risks"]) + "</ul></section>")
    body.append("<section><h2>Important documents</h2><ul>" + "".join(
        f"<li>{esc(d['filename'])} <span class='muted'>· {d['records']} records</span></li>" for d in c.get("documents", [])) + "</ul></section>")
    if c.get("answered_questions"):
        body.append("<section><h2>Clarifications from the outgoing member</h2>" + "".join(
            f"<div class='qa'><b>Q.</b> {esc(x['q'])}<br><b>A.</b> {esc(x['a'])}</div>" for x in c["answered_questions"]) + "</section>")
    if c.get("open_questions"):
        body.append("<section><h2>Still unanswered</h2><ul>" + "".join(
            f"<li><span class='sev {esc(q['severity'])}'>{esc(q['severity'])}</span> {esc(q['q'])}</li>" for q in c["open_questions"]) + "</ul></section>")
    if meta.get("manager_note"):
        body.append(f"<section><h2>Manager note</h2><p>{esc(meta['manager_note'])}</p></section>")
    body.append(f"<footer>Generated by ContinuityIQ · {datetime.now():%d %b %Y %H:%M} · every R-number points to a reviewed source record.</footer>")
    return f"""<!DOCTYPE html><html><head><meta charset="utf-8"><title>Handover – {esc(c['project']['name'])}</title>
<style>
body{{font-family:Inter,Segoe UI,system-ui,sans-serif;color:#1d2433;max-width:900px;margin:32px auto;padding:0 24px;line-height:1.55}}
header{{border-bottom:3px solid #4f46e5;padding-bottom:16px;margin-bottom:8px}} .brand{{color:#4f46e5;font-weight:700;font-size:13px;letter-spacing:.06em;text-transform:uppercase}}
h1{{margin:6px 0 10px;font-size:30px}} h2{{font-size:18px;margin:26px 0 8px;color:#111827}} .meta{{display:flex;gap:18px;flex-wrap:wrap;color:#4b5563;font-size:14px}}
.badge{{padding:2px 10px;border-radius:99px;font-size:12px;font-weight:700}} .badge.approved{{background:#dcfce7;color:#166534}} .badge.draft{{background:#fef3c7;color:#92400e}}
.cite{{background:#eef2ff;color:#4338ca;border-radius:4px;padding:0 4px;font-size:10px;font-weight:700;cursor:help}} .src{{color:#6b7280;font-size:12px}}
li{{margin:6px 0}} .muted{{color:#6b7280}} .count{{background:#f3f4f6;border-radius:99px;padding:1px 9px;font-size:12px;color:#374151}}
.grid2{{display:grid;grid-template-columns:1fr 1fr;gap:24px}} .qa{{background:#f9fafb;border-left:3px solid #4f46e5;padding:8px 12px;margin:8px 0;border-radius:4px}}
.sev{{font-size:11px;font-weight:700;text-transform:uppercase;padding:1px 6px;border-radius:4px;background:#fee2e2;color:#991b1b}} .sev.medium{{background:#fef3c7;color:#92400e}} .sev.low{{background:#e5e7eb;color:#374151}}
footer{{margin:40px 0 20px;color:#9ca3af;font-size:12px;border-top:1px solid #e5e7eb;padding-top:12px}}
@media print{{body{{margin:0}} .grid2{{display:block}}}}
</style></head><body>{''.join(body)}</body></html>"""


def to_pdf(c: dict, meta: dict) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import ListFlowable, ListItem, Paragraph, SimpleDocTemplate, Spacer

    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], alignment=0, fontSize=22, textColor=colors.HexColor("#111827"))
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=colors.HexColor("#4f46e5"), spaceBefore=10)
    p = ParagraphStyle("p", parent=ss["BodyText"], fontSize=10, leading=14)
    small = ParagraphStyle("s", parent=p, fontSize=8, textColor=colors.HexColor("#6b7280"))
    e = lambda t: html.escape(str(t))
    cite = lambda t: re.sub(r"\[R(\d+)\]", r'<font color="#4338ca" size="7"><b>[R\1]</b></font>', e(t))

    def bullets(lines, numbered=False):
        if not lines:
            return [Paragraph("None recorded.", small)]
        return [ListFlowable([ListItem(x, leftIndent=12) for x in lines], bulletType="1" if numbered else "bullet", start=1 if numbered else None, leftIndent=14)]

    story = [Paragraph("CONTINUITYIQ · HANDOVER REPORT", small), Paragraph(e(c["project"]["name"]), h1),
             Paragraph(f"From <b>{e(c.get('outgoing') or '-')}</b> to <b>{e(c.get('incoming') or '-')}</b> · "
                       f"Status: <b>{e(meta.get('status', 'draft')).upper()}</b> · Readiness: <b>{c.get('readiness', {}).get('score', 0)}%</b> · v{meta.get('version', 1)}", p),
             Spacer(1, 4 * mm), Paragraph("Project overview", h2), Paragraph(cite(c.get("overview", "")), p),
             Paragraph("Recommended next steps", h2), *bullets([Paragraph(cite(s), p) for s in c.get("next_steps", [])], True),
             Paragraph("First-week plan", h2), *bullets([Paragraph(cite(s), p) for s in c.get("first_week", [])])]
    for key, title in SECTIONS:
        story.append(Paragraph(f"{title} ({len(c.get(key, []))})", h2))
        story += bullets([Paragraph(f"{cite(_item_line(r))} <font color='#4338ca' size='7'><b>[R{r['id']}]</b></font><br/>"
                                    f"<font size='7' color='#6b7280'>{e(r['source'])}</font>", p) for r in c.get(key, [])])
    if c.get("risks"):
        story += [Paragraph("Risks to watch", h2), *bullets([Paragraph(cite(r), p) for r in c["risks"]])]
    story += [Paragraph("Important documents", h2), *bullets([Paragraph(f"{e(d['filename'])} · {d['records']} records", p) for d in c.get("documents", [])])]
    if c.get("answered_questions"):
        story.append(Paragraph("Clarifications from the outgoing member", h2))
        for x in c["answered_questions"]:
            story += [Paragraph(f"<b>Q.</b> {e(x['q'])}", p), Paragraph(f"<b>A.</b> {e(x['a'])}", p), Spacer(1, 2 * mm)]
    if c.get("open_questions"):
        story += [Paragraph("Still unanswered", h2), *bullets([Paragraph(f"({e(q['severity'])}) {e(q['q'])}", p) for q in c["open_questions"]])]
    if meta.get("manager_note"):
        story += [Paragraph("Manager note", h2), Paragraph(e(meta["manager_note"]), p)]
    story += [Spacer(1, 6 * mm), Paragraph(f"Generated by ContinuityIQ · {datetime.now():%d %b %Y %H:%M}", small)]
    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
                      title=f"Handover - {c['project']['name']}").build(story)
    return buf.getvalue()
